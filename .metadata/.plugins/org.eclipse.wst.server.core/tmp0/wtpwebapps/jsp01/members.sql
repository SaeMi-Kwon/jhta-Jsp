CREATE OR REPLACE PROCEDURE ADDMEMBER
(
	NUM MEMBERS.NUM%TYPE,
	NAME MEMBERS.NAME%TYPE,
	PHONE MEMBERS.PHONE%TYPE,
	ADDR MEMBERS.ADDR%TYPE
)
IS
BEGIN
	INSERT INTO MEMBERS VALUES(NUM,NAME,PHONE,ADDR,SYSDATE);
	COMMIT;
END ;
/

