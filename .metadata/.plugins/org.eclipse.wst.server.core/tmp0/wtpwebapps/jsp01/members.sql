CREATE OR REPLACE PROCEDURE DELMEMBER
(
	NUM1 MEMBERS.NUM%TYPE
)
IS
BEGIN
    DELETE FROM POINT WHERE NUM=NUM1;
	DELETE FROM MEMBERS WHERE NUM=NUM1;
	COMMIT;
END ;
/

